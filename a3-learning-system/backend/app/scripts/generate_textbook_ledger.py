def generate(output_path: str = None):
    wb = Workbook()
    header_font = Font(bold=True, size=11, color="FFFFFF")
    header_fill = PatternFill(start_color="4472C4", fill_type="solid")
    green_font = Font(color="008000")
    orange_font = Font(color="FF8C00")
    thin_border = Border(left=Side(style='thin'), right=Side(style='thin'), top=Side(style='thin'), bottom=Side(style='thin'))

    # Sheet 1: 核心教材
    ws1 = wb.active
    ws1.title = "核心教材(45本)"
    headers = ["序号","教材名称","出版社","ISBN","学科","章节","目标字数(万)","入库状态"]
    for col in range(1,9):
        c = ws1.cell(row=1, column=col, value=headers[col-1])
        c.font = header_font; c.fill = header_fill; c.alignment = Alignment(horizontal='center'); c.border = thin_border
    for i, t in enumerate(TEXTBOOKS, 1):
        for j, v in enumerate(t, 1):
            c = ws1.cell(row=i+1, column=j, value=v)
            c.border = thin_border
            if j == 8:
                c.font = orange_font if v == "待入库" else green_font
    ws1.column_dimensions['B'].width = 40; ws1.column_dimensions['C'].width = 20; ws1.column_dimensions['D'].width = 22

    # Sheet 2: 习题辅导
    ws2 = wb.create_sheet("习题辅导(20本)")
    h2 = ["序号","教材名称","出版社","ISBN","学科","类型","入库状态"]
    for col in range(1,8):
        c = ws2.cell(row=1, column=col, value=h2[col-1])
        c.font = header_font; c.fill = header_fill; c.alignment = Alignment(horizontal='center'); c.border = thin_border
    for i, t in enumerate(EXERCISE_BOOKS, 1):
        for j, v in enumerate(t, 1):
            c = ws2.cell(row=i+1, column=j, value=v)
            c.border = thin_border
            if j == 7: c.font = orange_font if v == "待入库" else green_font
    ws2.column_dimensions['B'].width = 45

    # Sheet 3: 课件实训
    ws3 = wb.create_sheet("课件实训(7份)")
    h3 = ["序号","资料名称","来源","类型","入库状态"]
    for col in range(1,6):
        c = ws3.cell(row=1, column=col, value=h3[col-1])
        c.font = header_font; c.fill = header_fill; c.alignment = Alignment(horizontal='center'); c.border = thin_border
    for i, t in enumerate(COURSEWARE, 1):
        for j, v in enumerate(t, 1):
            c = ws3.cell(row=i+1, column=j, value=v)
            c.border = thin_border
            if j == 5: c.font = orange_font if v == "待入库" else green_font

    # Sheet 4: 汇总
    ws4 = wb.create_sheet("汇总")
    ws4.cell(row=1, column=1, value="类别").font = header_font; ws4.cell(row=1, column=1).fill = header_fill
    ws4.cell(row=1, column=2, value="数量").font = header_font; ws4.cell(row=1, column=2).fill = header_fill
    for i, (label, count) in enumerate([("核心主干教材",45),("配套习题辅导",20),("高校课件实训",7),("总计",72)], 2):
        ws4.cell(row=i, column=1, value=label).border = thin_border
        ws4.cell(row=i, column=2, value=count).border = thin_border
    ws4.column_dimensions['A'].width = 20

    if output_path is None:
        output_path = os.path.join(os.path.dirname(__file__), "..", "..", "..", "docs", "教材台账_72本.xlsx")
    wb.save(output_path)
    print(f"台账已生成: {output_path}")
    print(f"  核心教材: {len(TEXTBOOKS)} 本")
    print(f"  习题辅导: {len(EXERCISE_BOOKS)} 本")
    print(f"  课件实训: {len(COURSEWARE)} 份")

if __name__ == "__main__":
    generate()
